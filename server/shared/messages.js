export function translate(locale, key, vars) {
  const template = MESSAGES[locale]?.[key] ?? MESSAGES.fr[key] ?? key;
  return vars ? template.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match)) : template;
}

/** A theme text (announcement, hero) in Arabic when it is a known default; anything else is returned as typed. */
// Server messages that carry a product name or a number cannot be listed one by one.
const KNOWN_PATTERNS = [
  [/^(.+): stock insuffisant \((\d+) disponible\(s\)\)$/, (m) => `${m[1]}: المخزون غير كافٍ (${m[2]} متوفر)`],
  [/^Trop d'articles dans la commande \(maximum (\d+)\)$/, (m) => `عدد المنتجات في الطلب كبير جدًا (الحد الأقصى ${m[1]})`],
  [/^Produit non disponible \((.+)\)$/, (m) => `المنتج غير متوفر (${m[1]})`],
];

export function translateKnown(locale, text) {
  if (locale !== 'ar' || typeof text !== 'string') return text;
  if (AR_BY_FRENCH[text]) return AR_BY_FRENCH[text];
  for (const [pattern, build] of KNOWN_PATTERNS) {
    const m = text.match(pattern);
    if (m) return build(m);
  }
  return text;
}
