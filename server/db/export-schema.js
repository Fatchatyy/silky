/**
 * Writes server/db/schema.sql: the structure (no data) of the database DATABASE_URL points at, as produced by pg_dump.
 * schema.sql is what `npm run db:init` applies to a brand-new empty database (the startup migrations only extend tables that
 * already exist; none of them creates users, products or orders).
 *
 * Regenerate it from a database that has the current schema, for example the test database, after adding a migration:
 *   DATABASE_URL=postgres://.../silky_test npm run db:export-schema
 *
 * Needs the PostgreSQL client tools (pg_dump) on the PATH. Reads the database, never writes to it.
 */
import dotenv from 'dotenv';
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
dotenv.config({ path: path.join(here, '../../.env') });

const url = process.env.DATABASE_URL;
if (!url) {
  console.error('DATABASE_URL is not set.');
  process.exit(1);
}
const parsed = new URL(url);
const dbName = decodeURIComponent(parsed.pathname.slice(1));

const result = spawnSync(
  'pg_dump',
  ['--schema-only', '--no-owner', '--no-privileges', '-h', parsed.hostname, '-p', parsed.port || '5432', '-U', decodeURIComponent(parsed.username), '-d', dbName],
  { env: { ...process.env, PGPASSWORD: decodeURIComponent(parsed.password) }, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
);
if (result.error || result.status !== 0) {
  console.error('pg_dump failed:', result.error?.message || result.stderr);
  process.exit(1);
}

// Keep the file stable between runs and free of psql-only commands and tool versions.
const body = result.stdout
  .split('\n')
  .filter((line) => !line.startsWith('\\') && !/^-- Dumped (from|by) /.test(line))
  .join('\n');

const header = `-- Silky database structure (no data). Generated by server/db/export-schema.js from the database "${dbName}".
-- Apply it ONCE to a new, empty database with: npm run db:init
-- Do not edit by hand: change the schema with a startup migration (server/db/migrations), then regenerate this file.
`;
fs.writeFileSync(path.join(here, 'schema.sql'), header + body);
console.log(`server/db/schema.sql written from "${dbName}" (${body.split('\n').length} lines).`);
