// The security headers of the storefront, in one place. Pure (no Workers or Astro imports) so that BOTH users get the same list:
//  - src/middleware.ts puts them on the few responses the Worker itself builds (the admin shell, the 404, redirects);
//  - scripts/write_headers.mjs writes them into public/_headers, which Cloudflare applies to every static file (all the pages).
// CSP is report-only first (nothing is blocked until the site has been browsed with no report); 'unsafe-inline' scripts are
// needed by Astro's island loader.
export type HeaderContext = { api: string; media: string; production: boolean };

const origins = (...list: string[]) => list.filter(Boolean).join(' ');

export function contentSecurityPolicy({ api, media }: HeaderContext) {
  return [
    "default-src 'self'",
    "script-src 'self' 'unsafe-inline'",
    "style-src 'self' 'unsafe-inline'",
    "font-src 'self'",
    `img-src ${origins("'self'", 'data:', 'blob:', media)}`,
    `media-src ${origins("'self'", 'blob:', media)}`,
    `connect-src ${origins("'self'", api)}`,
    "frame-ancestors 'none'",
    "base-uri 'self'",
    "form-action 'self'",
  ].join('; ');
}

/** Headers for every response. A password-reset address carries a secret token: it is never sent as a referrer. */
export function securityHeaders(context: HeaderContext, { passwordReset = false } = {}): [string, string][] {
  const headers: [string, string][] = [
    ['X-Content-Type-Options', 'nosniff'],
    ['Referrer-Policy', passwordReset ? 'no-referrer' : 'strict-origin-when-cross-origin'],
    ['X-Frame-Options', 'DENY'],
    ['Permissions-Policy', 'camera=(), microphone=(), geolocation=(), payment=()'],
    ['Content-Security-Policy-Report-Only', contentSecurityPolicy(context)],
  ];
  if (context.production) headers.push(['Strict-Transport-Security', 'max-age=15552000; includeSubDomains']);
  return headers;
}

/** The admin panel is not a page of the site: noindex, never stored by a browser or a proxy. */
export const ADMIN_HEADERS: [string, string][] = [
  ['X-Robots-Tag', 'noindex, nofollow'],
  ['Cache-Control', 'no-store'],
];

/** The text of public/_headers (Cloudflare's format: a path line, then indented headers). */
export function headersFile(context: HeaderContext): string {
  const block = (path: string, list: [string, string][]) => `${path}\n${list.map(([name, value]) => `  ${name}: ${value}`).join('\n')}\n`;
  return [
    '# GENERATED by scripts/write_headers.mjs at build time (src/lib/securityHeaders.ts). Do not edit.',
    block('/*', securityHeaders(context)),
    block('/password-reset/*', [['Referrer-Policy', 'no-referrer']]),
    block('/ar/password-reset/*', [['Referrer-Policy', 'no-referrer']]),
    block('/admin', ADMIN_HEADERS),
    block('/admin/*', ADMIN_HEADERS),
    block('/redirects-map.json', [['X-Robots-Tag', 'noindex']]),
    block('/search-index.json', [['X-Robots-Tag', 'noindex']]),
    block('/build-info.json', [['X-Robots-Tag', 'noindex'], ['Cache-Control', 'no-cache']]),
  ].join('\n');
}
